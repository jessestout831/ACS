public class BlockLetters {
    public static void main(String[] args) {
        System.out.println("  J");
        System.out.println("  J");
        System.out.println("  J");
        System.out.print("J ");
        System.out.println("J");
        System.out.println(" J");
        System.out.println("\n SS");
        System.out.println("S");
        System.out.println(" S");
        System.out.println("  S");
        System.out.println("SS");
    }
}
